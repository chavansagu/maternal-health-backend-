"""
Mobilisation Routes
Tracks pregnant women who need a mobilisation follow-up (missed ANC/PMSMA/USG,
near-EDD, unreferred HRP). Cases are auto-generated by scheduler jobs
(see scheduler.py::job_generate_mobilisation_cases / job_generate_edd_action_cases).
Delivery-related cases follow a stage-wise workflow
(Pending -> Contacted -> Planned -> Mobilised -> Reached Facility -> Admitted).
No call/SMS/AI-call actions are included by design.
"""
from fastapi import APIRouter, Depends, HTTPException, Request, status
from sqlalchemy.orm import Session, joinedload
from sqlalchemy import case as sa_case, or_
from typing import Optional, List
from datetime import datetime
from pydantic import BaseModel

from database import get_db
from models import MobilisationCase, MobilisationAction, PregnantWoman, User, DeliveryPoint
from auth import get_current_active_user
from audit_utils import log_audit, get_client_info
from services.alert_rules import close_case_alerts

router = APIRouter(prefix="/mobilisation", tags=["Mobilisation"])


# ─── Constants ──────────────────────────────────────────────────────────────

STAGES = ["pending", "contacted", "planned", "mobilised", "reached_facility", "admitted"]
STAGE_LABELS = {
    "pending": "Pending",
    "contacted": "Contacted",
    "planned": "Planned",
    "mobilised": "Mobilised",
    "reached_facility": "Reached Facility",
    "admitted": "Admitted",
}
LOCATIONS = {"at_dp": "At DP", "not_at_dp": "Not at DP"}
CONTACT_STATUSES = {
    "beneficiary_reached": "Beneficiary reached",
    "family_reached": "Family reached",
    "not_reachable": "Not reachable",
}
# Stage workflow sirf delivery se jude cases par
DELIVERY_TRIGGERS = [
    "near_edd", "hrp_near_edd", "hrp_near_edd_not_mobilised",
    "edd_today_not_admitted", "edd_overdue_no_delivery", "hrp_unreferred",
]


# ─── Schemas ────────────────────────────────────────────────────────────────

class MarkMobilisedRequest(BaseModel):
    remarks: Optional[str] = None


class UpdateStageRequest(BaseModel):
    action_datetime: datetime
    mobilisation_stage: str
    current_location: str
    contact_status: str
    contact_number: Optional[str] = None
    selected_dp_id: int
    reason_not_completed: Optional[str] = None


# ─── Helpers ────────────────────────────────────────────────────────────────

def _scope_query_to_user(query, current_user: User):
    """Restrict the case list to what this role is allowed to see."""
    if current_user.role == "sub_centre":
        query = query.filter(MobilisationCase.sub_centre_id == current_user.sub_centre_id)
    elif current_user.role == "block":
        query = query.filter(MobilisationCase.block_id == current_user.block_id)
    elif current_user.role == "district":
        query = query.filter(MobilisationCase.district_id == current_user.district_id)
    # PMSMA/USG/DP roles don't own a mobilisation queue; district/block/sub_centre only.
    else:
        query = query.filter(MobilisationCase.id.is_(None))  # empty result for other roles
    return query


PRIORITY_ORDER = sa_case(
    (MobilisationCase.priority == "critical", 0),
    (MobilisationCase.priority == "red_flag", 1),
    (MobilisationCase.priority == "high", 2),
    else_=3,
)


def _responsible_map(db: Session, sub_centre_ids) -> dict:
    """sub_centre_id -> responsible Sub-centre (ANM) user name(s)."""
    ids = {i for i in sub_centre_ids if i}
    if not ids:
        return {}
    users = db.query(User).filter(
        User.role == "sub_centre",
        User.is_active == True,
        User.sub_centre_id.in_(ids),
    ).all()
    names = {}
    for u in users:
        names.setdefault(u.sub_centre_id, []).append(u.full_name)
    return {k: ", ".join(v) for k, v in names.items()}


def _serialize_case(case: MobilisationCase, responsible_map: dict = None) -> dict:
    pw = case.pregnant_woman
    return {
        "id": case.id,
        "pregnant_woman_id": case.pregnant_woman_id,
        "pregnant_woman_name": pw.full_name if pw else None,
        "mobile_number": pw.mobile_number if pw else None,
        "is_high_risk": pw.is_high_risk if pw else None,
        "edd_date": pw.edd_date if pw else None,
        "trigger_type": case.trigger_type,
        "trigger_detail": case.trigger_detail,
        "trigger_reference_id": case.trigger_reference_id,
        "priority": case.priority,
        "pending_action": case.pending_action or case.trigger_detail,
        "responsible_role": case.responsible_role,
        "responsible_user": (responsible_map or {}).get(case.sub_centre_id),
        "mobilisation_stage": case.mobilisation_stage,
        "mobilisation_stage_label": STAGE_LABELS.get(case.mobilisation_stage, case.mobilisation_stage),
        "current_location": case.current_location,
        "contact_status": case.contact_status,
        "contact_number": case.contact_number,
        "selected_dp_id": case.selected_dp_id,
        "selected_dp_name": case.selected_dp.name if case.selected_dp else None,
        "reason_not_completed": case.reason_not_completed,
        "stage_updated_at": case.stage_updated_at,
        "is_delivery_case": case.trigger_type in DELIVERY_TRIGGERS,
        "sub_centre_id": case.sub_centre_id,
        "block_id": case.block_id,
        "district_id": case.district_id,
        "status": case.status,
        "escalation_level": case.escalation_level,
        "escalated_at": case.escalated_at,
        "mobilised_by": case.mobilised_by,
        "mobilised_by_name": case.mobilised_by_user.full_name if case.mobilised_by_user else None,
        "mobilised_at": case.mobilised_at,
        "remarks": case.remarks,
        "created_at": case.created_at,
        "updated_at": case.updated_at,
    }


# ─── List / count / options (static routes upar, /{case_id} neeche) ─────────

@router.get("/")
async def get_mobilisation_cases(
    status_filter: Optional[str] = None,
    trigger_type: Optional[str] = None,
    escalation_level: Optional[str] = None,
    priority: Optional[str] = None,
    current_user: User = Depends(get_current_active_user),
    db: Session = Depends(get_db),
):
    """
    Red action list scoped to the caller's role, most urgent first
    (critical > red_flag > high > normal).
    Default (no status_filter): open cases (pending + escalated), plus delivery
    cases that are Mobilised / Reached Facility (they stay visible until admission).
    """
    query = db.query(MobilisationCase).options(
        joinedload(MobilisationCase.pregnant_woman),
        joinedload(MobilisationCase.mobilised_by_user),
    )
    query = _scope_query_to_user(query, current_user)

    if status_filter:
        query = query.filter(MobilisationCase.status == status_filter)
    else:
        query = query.filter(or_(
            MobilisationCase.status.in_(["pending", "escalated"]),
            (MobilisationCase.status == "mobilised")
            & (MobilisationCase.trigger_type.in_(DELIVERY_TRIGGERS))
            & (MobilisationCase.mobilisation_stage.in_(["mobilised", "reached_facility"])),
        ))

    if trigger_type:
        query = query.filter(MobilisationCase.trigger_type == trigger_type)

    if escalation_level:
        query = query.filter(MobilisationCase.escalation_level == escalation_level)

    if priority:
        query = query.filter(MobilisationCase.priority == priority)

    cases = query.order_by(
        PRIORITY_ORDER,
        MobilisationCase.created_at.asc(),
    ).all()

    resp_map = _responsible_map(db, [c.sub_centre_id for c in cases])
    return [_serialize_case(c, resp_map) for c in cases]


@router.get("/count")
async def get_mobilisation_count(
    current_user: User = Depends(get_current_active_user),
    db: Session = Depends(get_db),
):
    """Quick count for dashboard 'mobilisation needed' KPI cards."""
    query = db.query(MobilisationCase).filter(
        MobilisationCase.status.in_(["pending", "escalated"])
    )
    query = _scope_query_to_user(query, current_user)
    return {"count": query.count()}


@router.get("/stage-options")
async def get_stage_options(current_user: User = Depends(get_current_active_user)):
    """Dropdown values for the stage form."""
    return {
        "stages": [{"value": s, "label": STAGE_LABELS[s]} for s in STAGES if s != "admitted"],
        "locations": [{"value": k, "label": v} for k, v in LOCATIONS.items()],
        "contact_statuses": [{"value": k, "label": v} for k, v in CONTACT_STATUSES.items()],
    }


# ─── Single case ────────────────────────────────────────────────────────────

@router.get("/{case_id}")
async def get_mobilisation_case(
    case_id: int,
    current_user: User = Depends(get_current_active_user),
    db: Session = Depends(get_db),
):
    case = db.query(MobilisationCase).options(
        joinedload(MobilisationCase.pregnant_woman),
        joinedload(MobilisationCase.mobilised_by_user),
    ).filter(MobilisationCase.id == case_id).first()

    if not case:
        raise HTTPException(status_code=404, detail="Mobilisation case not found")

    return _serialize_case(case, _responsible_map(db, [case.sub_centre_id]))


@router.get("/{case_id}/history")
async def get_case_history(
    case_id: int,
    current_user: User = Depends(get_current_active_user),
    db: Session = Depends(get_db),
):
    """Stage update log for a case (newest first)."""
    case = _scope_query_to_user(
        db.query(MobilisationCase).filter(MobilisationCase.id == case_id), current_user
    ).first()
    if not case:
        raise HTTPException(status_code=404, detail="Mobilisation case not found")

    rows = (
        db.query(MobilisationAction, User.full_name, DeliveryPoint.name)
        .outerjoin(User, User.id == MobilisationAction.recorded_by)
        .outerjoin(DeliveryPoint, DeliveryPoint.id == MobilisationAction.selected_dp_id)
        .filter(MobilisationAction.case_id == case_id)
        .order_by(MobilisationAction.action_datetime.desc(), MobilisationAction.id.desc())
        .all()
    )
    return [
        {
            "id": a.id,
            "action_datetime": a.action_datetime,
            "mobilisation_stage": a.mobilisation_stage,
            "mobilisation_stage_label": STAGE_LABELS.get(a.mobilisation_stage, a.mobilisation_stage),
            "current_location": a.current_location,
            "contact_status": a.contact_status,
            "contact_number": a.contact_number,
            "selected_dp_id": a.selected_dp_id,
            "selected_dp_name": dp_name,
            "reason_not_completed": a.reason_not_completed,
            "recorded_by": a.recorded_by,
            "recorded_by_name": user_name,
        }
        for a, user_name, dp_name in rows
    ]


# ─── Stage-wise update (spec J) ─────────────────────────────────────────────

@router.post("/{case_id}/update-stage")
async def update_stage(
    case_id: int,
    body: UpdateStageRequest,
    request: Request,
    current_user: User = Depends(get_current_active_user),
    db: Session = Depends(get_db),
):
    """Stage-wise mobilisation update (Pending -> ... -> Reached Facility). Admitted is automatic."""
    case = _scope_query_to_user(
        db.query(MobilisationCase).filter(MobilisationCase.id == case_id), current_user
    ).first()
    if not case:
        raise HTTPException(status_code=404, detail="Mobilisation case not found")
    if case.status == "closed" or case.mobilisation_stage == "admitted":
        raise HTTPException(status_code=400, detail="This case is already closed / admitted")
    if case.trigger_type not in DELIVERY_TRIGGERS:
        raise HTTPException(status_code=400, detail="Stage workflow is only for delivery-related cases")

    errors = []
    stage = body.mobilisation_stage
    current_stage = case.mobilisation_stage or "pending"

    if stage not in STAGES:
        errors.append("Invalid mobilisation stage")
    elif stage == "admitted":
        errors.append("Admitted is set automatically when the facility records the admission")
    elif STAGES.index(stage) < STAGES.index(current_stage):
        errors.append("Stage cannot move backwards")

    if body.current_location not in LOCATIONS:
        errors.append("Current location is required (At DP / Not at DP)")
    if body.contact_status not in CONTACT_STATUSES:
        errors.append("Contact / follow-up status is required")
    if stage == "pending" and not (body.reason_not_completed or "").strip():
        errors.append("Reason is required when the stage is Pending")

    pw = case.pregnant_woman
    dp = db.query(DeliveryPoint).filter(
        DeliveryPoint.id == body.selected_dp_id, DeliveryPoint.is_active == True
    ).first()
    if not dp:
        errors.append("Selected delivery point not found")
    elif pw and pw.is_high_risk and not dp.is_sdh_dhh:
        errors.append("High-risk cases can only select a higher institution (SDH/DHH)")

    if errors:
        raise HTTPException(status_code=400, detail="; ".join(errors))

    contact_number = (body.contact_number or "").strip() or (pw.mobile_number if pw else None)
    reason = (body.reason_not_completed or "").strip() or None
    old_values = {"mobilisation_stage": current_stage, "status": case.status}

    case.mobilisation_stage = stage
    case.current_location = body.current_location
    case.contact_status = body.contact_status
    case.contact_number = contact_number
    case.selected_dp_id = dp.id
    case.reason_not_completed = reason
    case.stage_updated_at = datetime.now()

    # Mobilised ya usse aage: purane 'mobilised' status se compatible rakho
    if STAGES.index(stage) >= STAGES.index("mobilised"):
        case.status = "mobilised"
        if not case.mobilised_at:
            case.mobilised_by = current_user.id
            case.mobilised_at = body.action_datetime

    db.add(MobilisationAction(
        case_id=case.id,
        action_datetime=body.action_datetime,
        mobilisation_stage=stage,
        current_location=body.current_location,
        contact_status=body.contact_status,
        contact_number=contact_number,
        selected_dp_id=dp.id,
        reason_not_completed=reason,
        recorded_by=current_user.id,
    ))
    db.commit()
    db.refresh(case)
    if case.status in ("mobilised", "closed"):
        # Required entry (mobilisation) done -> close the alert (spec M)
        close_case_alerts(db, [case.id], note=f"Mobilisation stage: {stage}", commit=True)

    ip_address, user_agent = get_client_info(request)
    log_audit(
        db=db,
        user_id=current_user.id,
        action="MOBILISATION_STAGE_UPDATED",
        entity_type="MobilisationCase",
        entity_id=case.id,
        old_values=old_values,
        new_values={"mobilisation_stage": stage, "selected_dp_id": dp.id},
        ip_address=ip_address,
        user_agent=user_agent,
    )

    return _serialize_case(case, _responsible_map(db, [case.sub_centre_id]))


# ─── Old simple "mark mobilised" (sirf non-delivery cases ke liye) ──────────

@router.post("/{case_id}/mark-mobilised")
async def mark_mobilised(
    case_id: int,
    body: MarkMobilisedRequest,
    request: Request,
    current_user: User = Depends(get_current_active_user),
    db: Session = Depends(get_db),
):
    """
    Mark a non-delivery case (missed ANC / PMSMA / USG) as done. Anyone in scope
    (ANM/Block/District) can close a case they can see.
    Delivery-related cases use /update-stage instead.
    """
    case = db.query(MobilisationCase).filter(MobilisationCase.id == case_id).first()
    if not case:
        raise HTTPException(status_code=404, detail="Mobilisation case not found")

    if case.trigger_type in DELIVERY_TRIGGERS:
        raise HTTPException(status_code=400, detail="Use the stage update for delivery-related cases")
    if case.status == "mobilised":
        raise HTTPException(status_code=400, detail="Case is already marked as mobilised")
    if case.status == "closed":
        raise HTTPException(status_code=400, detail="Case is already closed")

    old_values = {"status": case.status, "escalation_level": case.escalation_level}

    case.status = "mobilised"
    case.mobilised_by = current_user.id
    case.mobilised_at = datetime.now()
    case.remarks = body.remarks

    db.commit()
    db.refresh(case)
    close_case_alerts(db, [case.id], note="Marked as mobilised", commit=True)

    ip_address, user_agent = get_client_info(request)
    log_audit(
        db=db,
        user_id=current_user.id,
        action="MOBILISATION_MARKED_DONE",
        entity_type="MobilisationCase",
        entity_id=case.id,
        old_values=old_values,
        new_values={"status": case.status, "remarks": case.remarks},
        ip_address=ip_address,
        user_agent=user_agent,
    )

    return _serialize_case(case, _responsible_map(db, [case.sub_centre_id]))